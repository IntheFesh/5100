def write_t1(path, roles, A, fam):
    pretty = {"public": "public PQN", "fixed2": "fixed PQN, $E=2$", "fixedBest": "fixed PQN, $E^*$", "ours": "ours"}
    L = ["\\begin{tabular}{lrrrr}", "\\toprule", "arm & robust AUC [95\\% CI] & final return & train AUC & public-protocol AUC \\\\", "\\midrule"]
    for role, arm in roles.items():
        if arm is None:
            continue
        o, t, g = A["robust"]["configs"][arm], A["train"]["configs"][arm], A["greedy"]["configs"][arm]
        L.append(f"{pretty[role]} & {o['auc_mean']:.1f} {tex_ci(o['auc_ci'])} & {o['final_mean']:.1f} & {t['auc_mean']:.1f} & {g['auc_mean']:.1f} \\\\")
    L += ["\\midrule", "\\multicolumn{5}{l}{\\emph{paired differences (10 seeds; Student-$t$ CI; exact sign-flip test, one Holm family)}} \\\\",
          "comparison & $\\Delta$AUC [95\\% CI] & relative & Holm $p$ & substantial? \\\\", "\\midrule"]
    for key, label in (("C1", "fixed $E{=}2$ vs public"), ("C3", "ours vs fixed $E{=}2$"), ("CTRL", "ours vs fixed $E^*$"), ("C3H", "fixed $E^*$ vs fixed $E{=}2$")):
        p = fam.get(key)
        if p is None:
            continue
        L.append(f"{label} & {p['diff_mean']:+.1f} {tex_ci(p['diff_ci'])} & {tex_pct(p['diff_rel'])} & {tex_p(p.get('p_holm'))} & {'yes' if large_improvement(p) else 'no'} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", ""]
    open(path, "w").write("\n".join(L))


def write_t2(path, p3):
    L = ["\\begin{tabular}{llrl}", "\\toprule", "game & arm & AUC (mean) & per-seed AUC ($n{=}5$, descriptive only) \\\\", "\\midrule"]
    for game, arms in p3.items():
        for arm, o in arms.items():
            L.append(f"{game} & {arm.replace('_', ' ')} & {o['auc_mean']:.1f} & {', '.join(f'{v:.1f}' for v in o['auc_per_seed'])} \\\\")
        L.append("\\midrule")
    L[-1] = "\\bottomrule"; L += ["\\end{tabular}", ""]
    open(path, "w").write("\n".join(L))


# ---------------------------------------------------------------------------------------------------------- claims
def claims_md(path, C):
    S = lambda ok: "satisfied" if ok else "NOT satisfied"
    L = ["# CLAIMS (plan table 1): evidence, numbers, whether the required evidence is met, wording if not\n",
         f"Generated by `make_paper_assets.py`; every number is from `paper/numbers.json` (macro names in brackets). Mode of the frozen P2: **{C['mode']}**.\n"]
    for k in ("C0", "C1", "C2", "C3", "C4"):
        c = C[k]
        L += [f"## {k} - {c['title']}\n", f"- **Required evidence:** {c['required']}", f"- **Evidence / numbers:** {c['evidence']}", f"- **Verdict:** {S(c['ok'])}" + (f" ({c['note']})" if c.get("note") else ""),
              f"- **If not satisfied (plan):** {c['downgrade']}", f"- **Wording to use now:** {c['wording']}\n"]
    L += ["## Which statements may use \"substantial / large improvement\"?\n", "Rule (plan section 2): >= 25 % relative AUC gain, paired 95 % CI excludes 0, Holm p < 0.05, 10 confirmation seeds.\n",
          "| comparison | relative | 95% CI of dAUC | Holm p | may use the phrase? |", "|---|---|---|---|---|"]
    for key, label in (("C1", "fixed E=2 vs public (C1)"), ("C3", "ours vs fixed E=2 (C3)"), ("CTRL", "ours vs fixed E* (control itself)"), ("C3H", "fixed E* vs fixed E=2 (no control)")):
        p = C["fam"].get(key)
        if p:
            L.append(f"| {label} | {p['diff_rel'] * 100:+.1f}% | {tex_ci(p['diff_ci'])} | {tex_p(p.get('p_holm'))} | **{'YES' if large_improvement(p) else 'no - report the effect size and interval only'}** |")
    open(path, "w").write("\n".join(L) + "\n")


