"""make_paper_assets.py - ONE command rebuilds every figure, table, number macro and the claims table of the paper from results/ (round 8).

Usage:  python make_paper_assets.py [--results results] [--frozen frozen_P2.json] [--paper paper] [--require_tag]
Inputs  results/P0, results/P1, results/P2 [, results/P3]  (JSONs of sweep.py), frozen_P2.json + docs/FREEZE.md (P2 freeze), results/P1_selection/selection.json (optional)
Outputs paper/figs/F1_protocol, F2_ladder, F3_mechanism, F4_main, F5_wd_equilibrium (.pdf, .png), paper/figs/T1_main.tex, T2_p3.tex,
        paper/numbers.tex (\\newcommand macros), paper/numbers.json, results/CLAIMS.md, results/analysis/*.json, results/mechanism_P1|P2/.
Rules:  every number in the paper is a macro defined here from a JSON; statistics (Student-t CIs, exact sign-flip p, Holm) are produced by
        analyze.py (--pairs = one Holm family) and mechanism.py - nothing statistical is recomputed in this file.
        'Substantial improvement' (plan section 2): relative AUC gain >= 25 %, paired 95 % CI excludes 0, Holm p < 0.05, 10 confirmation seeds.
        Refuses to run if the P2 JSON args differ from frozen_P2.json, if the sha256 in docs/FREEZE.md does not match, or (--require_tag) if the git tag freeze-P2 is missing.
"""
