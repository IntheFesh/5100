def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results")); ap.add_argument("--frozen", default=os.path.join(ROOT, "frozen_P2.json"))
    ap.add_argument("--freeze_md", default=os.path.join(ROOT, "docs", "FREEZE.md")); ap.add_argument("--paper", default=os.path.join(ROOT, "paper"))
    ap.add_argument("--require_tag", action="store_true", help="also require the git tag freeze-P2")
    a = ap.parse_args(argv)
    R = os.path.abspath(a.results); figs = os.path.join(a.paper, "figs"); ana = os.path.join(R, "analysis")
    os.makedirs(figs, exist_ok=True); os.makedirs(ana, exist_ok=True)
    p0d, p1d, p2d, p3d = (os.path.join(R, s) for s in ("P0", "P1", "P2", "P3"))
    problems, fz = verify_freeze(a.frozen, a.freeze_md, p2d, a.require_tag)
    if problems:
        sys.exit("STOP - the P2 freeze does not verify:\n" + "\n".join(" - " + p for p in problems))
    E = fz["best_E"]; arms = fz["p2_arms"]
    ours = next((n for n in arms if n.startswith("ours_")), None)
    roles = {"public": "public", "fixed2": "fixed_E2", "fixedBest": f"fixed_E{E}" if (E != 2 and f"fixed_E{E}" in arms) else None, "ours": ours}
    M = Macros()

    # ---- P0
    p0_runs = p0_report.load_stage(p0d); p0_prob, _, _ = p0_report.integrity(p0_runs)
    if p0_prob:
        sys.exit("P0 integrity problems:\n" + "\n".join(p0_prob))
    A0 = run_analyze(p0d, "robust_return", os.path.join(ana, "P0_robust_vs_public.json"), "--ref", "public")
    A0g = run_analyze(p0d, "robust_return", os.path.join(ana, "P0_robust_vs_public_gymnax.json"), "--ref", "public_gymnax")
    r4 = p0_report.stop_rule_4(A0)
    iqm = ["--iqm"] if r4["triggered"] else []
    for n, o in A0["configs"].items():
        M.add(camel("p0Auc", n), f"{o['auc_mean']:.1f}", o["auc_mean"], "P0 robust AUC")
        M.add(camel("p0AucCI", n), tex_ci(o["auc_ci"]), o["auc_ci"], "P0 robust AUC CI")
        if "diff_mean" in o:
            M.add(camel("p0DiffVsPublic", n), f"{o['diff_mean']:+.1f}", o["diff_mean"]); M.add(camel("p0RelVsPublic", n), tex_pct(o["diff_rel"]), o["diff_rel"])
            M.add(camel("p0PVsPublic", n), tex_p(o.get("p_holm")), o.get("p_holm"))
    for n, o in A0g["configs"].items():
        if "diff_rel" in o:
            M.add(camel("protoEffectRel", n), tex_pct(o["diff_rel"]), o["diff_rel"], "robust AUC of the arm relative to public_gymnax (protocol effect, not a method effect)")
    pg = p0_runs["public_gymnax"][0][1]["evals"]
    M.add("cappedFinalGymnax", f"{np.mean(pg[-1]['capped_frac']):.2f}", float(np.mean(pg[-1]["capped_frac"])), "public protocol, last eval, public_gymnax")
    M.add("cappedFinalRobustFixed", f"{np.mean(p0_runs['fixed'][0][1]['evals'][-1]['robust_capped_frac']):.2f}", float(np.mean(p0_runs['fixed'][0][1]['evals'][-1]['robust_capped_frac'])), "robust protocol, last eval, fixed")
    M.add("pZeroRuleFourTriggered", "yes" if r4["triggered"] else "no", r4["triggered"], "stopping rule 4")
    fig_f1(p0_runs, figs); fig_f2(A0, figs)

    # ---- P1 / mechanism
    m1 = os.path.join(R, "mechanism_P1")
    subprocess.run([sys.executable, os.path.join(ROOT, "mechanism.py"), p1d, "--out", m1], check=True, capture_output=True)
    subprocess.run([sys.executable, os.path.join(ROOT, "mechanism.py"), p2d, "--out", os.path.join(R, "mechanism_P2")], check=True, capture_output=True)
    V1 = json.load(open(os.path.join(m1, "verdicts.json")))
    runs1 = mechanism.load_runs(p1d)
    for E_ in (2, 4, 8):
        r = runs1.get(f"E{E_}_none")
        if r is not None:
            M.add(camel("lambdaEnd", f"E{E_}"), f"{np.mean(r.wn[-1] / 16.0):.2f}", float(np.mean(r.wn[-1] / 16.0)), "P1 mean Lambda at the last eval point")
