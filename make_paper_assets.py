# ---------------------------------------------------------------------------------------------------------- helpers
def letters(s):
    """LaTeX macro names may only contain letters: spell digits, drop everything else."""
    s = re.sub(r"\d", lambda m: DIGITS[int(m.group())].capitalize(), s)
    return re.sub(r"[^A-Za-z]", "", s)


def camel(*parts):
    parts = [letters(str(p)) for p in parts]
    return parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def tex_pct(x):
    return f"{x * 100:+.1f}\\%"


def tex_p(p):
    return "n/a" if p is None or (isinstance(p, float) and np.isnan(p)) else ("<0.001" if p < 0.001 else f"{p:.3f}")


def tex_ci(ci, f=".1f"):
    return "n/a" if ci is None or ci[0] is None or np.isnan(ci[0]) else f"[{ci[0]:{f}}, {ci[1]:{f}}]"


class Macros:
    def __init__(self):
        self.d = {}

    def add(self, name, text, value=None, source=""):
        assert re.fullmatch(r"[A-Za-z]+", name), name
        assert name not in self.d, f"duplicate macro {name}"
        self.d[name] = dict(text=str(text), value=value, source=source)

    def write(self, tex, js):
        with open(tex, "w") as f:
            f.write("% generated by make_paper_assets.py - do not edit\n")
            for k in sorted(self.d):
                f.write(f"\\newcommand{{\\{k}}}{{{self.d[k]['text']}}}\n")
        json.dump(self.d, open(js, "w"), indent=1, sort_keys=True, default=float)


def run_analyze(stage, metric, out, *extra):
    r = subprocess.run([sys.executable, os.path.join(ROOT, "analyze.py"), stage, "--metric", metric, "--json_out", out, *extra], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"analyze.py failed ({stage} {metric} {extra}):\n{r.stderr[-1500:]}")
    return json.load(open(out))


def sha256_file(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def large_improvement(p):
    """Plan section 2, fixed before any data: rel. gain >= 25 %, paired 95 % CI excludes 0 (above), exact sign-flip Holm p < 0.05, n = 10."""
    return bool(p["n"] >= 10 and p["diff_rel"] >= LARGE_REL and p["diff_ci"][0] > 0 and p.get("p_holm", 1.0) < ALPHA)


# ---------------------------------------------------------------------------------------------------------- freeze checks
def verify_freeze(frozen_path, freeze_md, p2_dir, require_tag):
    problems = []
    if not os.path.exists(frozen_path):
        return [f"{frozen_path} not found"], None
    fz = json.load(open(frozen_path))
    if os.path.exists(freeze_md):
        m = re.search(r"sha256: `([0-9a-f]{64})`", open(freeze_md).read())
        if not m or m.group(1) != sha256_file(frozen_path):
            problems.append(f"sha256 of {frozen_path} does not match {freeze_md}")
    else:
        problems.append(f"{freeze_md} not found")
    if require_tag:
        tags = subprocess.run(["git", "tag", "-l", "freeze-P2"], capture_output=True, text=True, cwd=ROOT).stdout.split()
        if "freeze-P2" not in tags:
            problems.append("git tag freeze-P2 does not exist")
    exp = {n: a for n, _, a in effective_rows("P2", fz["best_E"], fz["best_ctrl"])}
    got = p0_report.load_stage(p2_dir)
    want = fz["p2_arms"]
    for n in want:
        if n not in exp:
            problems.append(f"frozen arm {n} is not a config of `sweep.py P2 --best_E {fz['best_E']} --best_ctrl {fz['best_ctrl']!r}`"); continue
        if n not in got or len(got[n]) != 1:
            problems.append(f"P2 config {n} missing or duplicated"); continue
        a = got[n][0][1]["args"]
        diff = {k: (a.get(k, "<absent>"), v) for k, v in exp[n].items() if k not in p0_report.SKIP_KEYS | {"save_params", "ckpt_at"} and a.get(k, "<absent>") != v}
        if diff:
            problems.append(f"P2 config {n}: args differ from the frozen configuration: {diff}")
        if got[n][0][1].get("seed_ids") != list(range(1000, 1010)):
            problems.append(f"P2 config {n}: seed_ids {got[n][0][1].get('seed_ids')} != 1000-1009")
    extra = [n for n in got if n not in want]
    if extra:
        problems.append(f"P2 contains configs that are not in the frozen arms: {extra}")
    return problems, fz


